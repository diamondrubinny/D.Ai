"""Translation catalogs without extra tools: extract → .pot, read .po, write .mo.

Extraction reads the apps' source (never imports or runs it) and collects
every English/Hebrew pair:
  - ("English", "עברית") as a dict value, or in a list that is a dict value;
  - the last two arguments of a call: _l(lang, "English", "עברית");
  - "עברית" if lang == "he" else "English" (either order).
A line marked `# i18n: command` is skipped: Tune sentences and Forge examples
must stay in a language the rule parsers understand (docs/I18N.md §2.4).
"""

from __future__ import annotations

import ast
import re
import struct
from dataclasses import dataclass, field
from pathlib import Path

from . import DOMAIN, _fields

HEBREW = re.compile(r"[\u0590-\u05ff]")
LATIN = re.compile(r"[A-Za-z]")
SKIP_MARK = "# i18n: command"


@dataclass
class Entry:
    msgid: str
    hebrew: str
    refs: list[str] = field(default_factory=list)


def _const(node: ast.AST) -> str | None:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _pair(en_node: ast.AST, he_node: ast.AST) -> tuple[str, str] | None:
    en, he = _const(en_node), _const(he_node)
    if en is None or he is None or not HEBREW.search(he) or HEBREW.search(en) or not LATIN.search(en):
        return None
    return en, he


def _is_he_test(test: ast.AST) -> bool | None:
    """lang == "he" -> True, lang == "en" -> False, anything else -> None."""
    if isinstance(test, ast.Compare) and len(test.ops) == 1 and isinstance(test.ops[0], ast.Eq):
        value = _const(test.comparators[0])
        return {"he": True, "en": False}.get(value or "")
    return None


def pairs_in_source(source: str, filename: str) -> list[tuple[str, str, int]]:
    tree = ast.parse(source, filename)
    lines = source.splitlines()
    parents: dict[ast.AST, ast.AST] = {}
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            parents[child] = node
    found = []
    for node in ast.walk(tree):
        pair = None
        if isinstance(node, ast.Tuple) and len(node.elts) == 2:
            parent = parents.get(node)
            if isinstance(parent, (ast.List, ast.Tuple)):
                parent = parents.get(parent)
            if isinstance(parent, ast.Dict):
                pair = _pair(*node.elts)
        elif isinstance(node, ast.Call) and len(node.args) >= 2:
            pair = _pair(*node.args[-2:])
        elif isinstance(node, ast.IfExp):
            he_first = _is_he_test(node.test)
            if he_first is not None:
                pair = _pair(node.orelse, node.body) if he_first else _pair(node.body, node.orelse)
        if pair is None:
            continue
        line = lines[node.lineno - 1] if node.lineno <= len(lines) else ""
        if SKIP_MARK in line:
            continue
        found.append((pair[0], pair[1], node.lineno))
    return found


def extract(roots: list[Path], base: Path) -> list[Entry]:
    entries: dict[str, Entry] = {}
    for root in roots:
        for path in sorted(root.rglob("*.py")):
            if "tests" in path.parts:
                continue
            rel = path.relative_to(base).as_posix()
            for en, he, line in pairs_in_source(path.read_text(encoding="utf-8"), rel):
                entry = entries.setdefault(en, Entry(en, he))
                entry.refs.append(f"{rel}:{line}")
    return sorted(entries.values(), key=lambda e: e.msgid)


def _quote(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n")
    return f'"{escaped}"'


def render_pot(entries: list[Entry]) -> str:
    out = [
        "# D.Ai OS interface texts. Copyright (c) 2026 Diamond Rubinny (d.Ai). Apache-2.0.",
        "# Generated by: python3 -m dai_i18n.tool extract (do not edit by hand).",
        "# Translate into i18n/po/<lang>.po; keep every {placeholder} exactly as it is.",
        'msgid ""',
        'msgstr ""',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        "",
    ]
    for entry in entries:
        out.append(f"#. he: {entry.hebrew}".replace("\n", " "))
        out.extend(f"#: {ref}" for ref in entry.refs[:5])
        if _fields(entry.msgid):
            out.append("#, python-brace-format")
        out.append(f"msgid {_quote(entry.msgid)}")
        out.append('msgstr ""')
        out.append("")
    return "\n".join(out)


_UNESCAPE = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}


def _unquote(token: str) -> str:
    body = token.strip()
    if len(body) < 2 or body[0] != '"' or body[-1] != '"':
        raise ValueError(f"not a quoted string: {token[:40]}")
    return re.sub(r'\\(.)', lambda m: _UNESCAPE.get(m.group(1), m.group(1)), body[1:-1])


def parse_po(text: str) -> dict[str, str]:
    """msgid -> msgstr; fuzzy and untranslated entries are left out (like msgfmt)."""
    messages: dict[str, str] = {}
    fuzzy = False
    current: dict[str, str] = {}
    key = None

    def flush() -> None:
        nonlocal fuzzy
        if "msgid" in current and current.get("msgstr") and current["msgid"] and not fuzzy:
            messages[current["msgid"]] = current["msgstr"]
        current.clear()
        fuzzy = False

    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if key is not None and current.get("msgstr") is not None:
                flush()
                key = None
            if line.startswith("#,") and "fuzzy" in line:
                fuzzy = True
            continue
        if line.startswith("msgid "):
            if "msgstr" in current:
                flush()
            key = "msgid"
            current[key] = _unquote(line[6:])
        elif line.startswith("msgstr "):
            key = "msgstr"
            current[key] = _unquote(line[7:])
        elif line.startswith('"') and key:
            current[key] += _unquote(line)
        else:
            raise ValueError(f"unexpected line in .po: {line[:60]}")
    flush()
    return messages


def write_mo(messages: dict[str, str], lang: str) -> bytes:
    """GNU .mo (what gettext reads), with a UTF-8 header."""
    catalog = {"": f"Content-Type: text/plain; charset=UTF-8\nLanguage: {lang}\n", **messages}
    keys = sorted(catalog)
    ids = [k.encode("utf-8") for k in keys]
    strs = [catalog[k].encode("utf-8") for k in keys]
    count = len(keys)
    start = 7 * 4 + count * 16
    id_data, str_data = b"", b""
    id_index, str_index = [], []
    for raw in ids:
        id_index.append((len(raw), start + len(id_data)))
        id_data += raw + b"\0"
    offset = start + len(id_data)
    for raw in strs:
        str_index.append((len(raw), offset + len(str_data)))
        str_data += raw + b"\0"
    header = struct.pack("<7I", 0x950412DE, 0, count, 28, 28 + count * 8, 0, 0)
    table = b"".join(struct.pack("<2I", *pair) for pair in id_index + str_index)
    return header + table + id_data + str_data


def problems(messages: dict[str, str], known: set[str]) -> list[str]:
    """What would make a translation unusable: unknown texts, or placeholders that differ."""
    out = []
    for msgid, msgstr in messages.items():
        if msgid not in known:
            out.append(f"not in {DOMAIN}.pot (stale?): {msgid[:60]!r}")
        elif _fields(msgstr) != _fields(msgid):
            out.append(f"placeholders differ from the English text: {msgid[:60]!r}")
    return out
