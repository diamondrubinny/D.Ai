"""Builds the website (docs/SITE.md) from one source in eight languages.

  python3 build/scripts/site-build.py [--check]

  site/src/strings/<lang>.json      the landing page's words, one file per language
  site/src/legal/<he|en>/<page>.html  privacy, terms and accessibility (the body only)

Writes site/index.html (Hebrew), site/<lang>/index.html, site/<page>.html (Hebrew legal pages) and
site/en/<page>.html. The language switcher and hreflang alternates come from site-languages.py, so both
scripts agree. --check exits 1 when a written page differs from what the source gives (the site test runs it).
The strings are our own content, written as HTML on purpose (links, <code>, <strong>); nothing here comes
from visitors.
"""
from __future__ import annotations

import html
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "site"
SRC = SITE / "src"
DOMAIN = "https://rubinny.com"
GITHUB = "https://github.com/diamondrubinny/D.Ai"
LATEST = f"{GITHUB}/releases/latest"
CSP = ("default-src 'self'; img-src 'self'; style-src 'self'; script-src 'none'; object-src 'none'; "
       "base-uri 'none'; form-action 'none'")
LEGAL_PAGES = ("privacy", "terms", "accessibility")
MARK = {"ok": "✓", "part": "≈", "no": "✗"}

_spec = importlib.util.spec_from_file_location("site_languages", Path(__file__).with_name("site-languages.py"))
languages = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(languages)


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def head(s: dict, title: str, description: str, prefix: str, url: str, alternates: str = "") -> str:
    return f"""<!DOCTYPE html>
<!-- SPDX-License-Identifier: Apache-2.0 -->
<!-- Copyright (c) 2026 Diamond Rubinny (d.Ai) -->
<!-- Generated by build/scripts/site-build.py from site/src: edit the source, not this file. -->
<html lang="{s['lang']}" dir="{s['dir']}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{esc(title)}</title>
  <meta name="description" content="{esc(description)}">
  <meta property="og:type" content="website">
  <meta property="og:url" content="{url}">
  <meta property="og:title" content="{esc(title)}">
  <meta property="og:description" content="{esc(description)}">
  <meta property="og:image" content="{DOMAIN}/img/og.jpg">
  <meta property="og:locale" content="{s['locale']}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="color-scheme" content="dark">
  <meta name="theme-color" content="#0B1020">
  <!-- No scripts, cookies, trackers or third-party resources on this site. -->
  <meta http-equiv="Content-Security-Policy" content="{CSP}">
  <meta name="referrer" content="no-referrer">
  <link rel="icon" href="{prefix}dai-logo.svg" type="image/svg+xml">{alternates}
  <link rel="stylesheet" href="{prefix}style.css">
</head>
"""


def top(s: dict, prefix: str, home: str, nav: str = "") -> str:
    return f"""<body>
  <a class="skip" href="#main">{esc(s['skip'])}</a>
  <header class="top">
    <div class="wrap bar">
      <a class="brand" href="{home}"><img src="{prefix}dai-logo.svg" alt="" width="36" height="36"><span>D.Ai OS</span></a>{nav}
    </div>
  </header>
"""


def legal_href(s: dict, folder: str, page: str) -> str:
    """Hebrew has its legal pages at the root, English in en/; the other languages link to the English ones."""
    if s["lang"] == "he":
        return f"{page}.html"
    return f"{page}.html" if folder == "en" else f"../en/{page}.html"


def footer(s: dict, folder: str, switcher: str) -> str:
    f = s["footer"]
    links = " ".join(f'<a href="{legal_href(s, folder, page)}">{esc(f[page])}</a>' for page in LEGAL_PAGES)
    return f"""  <footer>
    <div class="wrap">
      <nav aria-label="{esc(f['label'])}">{links} <a href="{GITHUB}">{esc(f['source'])}</a></nav>
      <p><bdi>© 2026 Diamond Rubinny (d.Ai) · D.Ai OS</bdi> · {f['line']}</p>
      {switcher}
    </div>
  </footer>
</body>
</html>
"""


def figure(src: str, w: int, h: int, alt: str, prefix: str, lazy: bool = True, caption: str = "") -> str:
    loading = ' loading="lazy" decoding="async"' if lazy else ' fetchpriority="high"'
    cap = f"<figcaption>{esc(caption)}</figcaption>" if caption else ""
    return (f'<figure class="frame"><img src="{prefix}img/{src}.webp" width="{w}" height="{h}"{loading} '
            f'alt="{esc(alt)}">{cap}</figure>')


def status(kind: str, text: str) -> str:
    return f'<span class="st {kind}"><span aria-hidden="true">{MARK[kind]}</span> {text}</span>'


def landing(s: dict, folder: str) -> str:
    prefix = "../" if folder else ""
    switcher, alternates = languages.render(s["lang"], folder)
    url = f"{DOMAIN}/{folder + '/' if folder else ''}"
    n, hero = s["nav"], s["hero"]
    nav = (f'\n      <nav class="main" aria-label="{esc(n["label"])}">'
           + "".join(f'<a href="#{key}">{esc(n[key])}</a>' for key in ("tour", "inside", "compare", "windows"))
           + f'<a class="btn small primary" href="#download">{esc(n["download"])}</a></nav>')
    out = [head(s, s["title"], s["description"], prefix, url, alternates), top(s, prefix, "#main", nav)]

    chips = "".join(f"<li>{esc(chip)}</li>" for chip in hero["chips"])
    out.append(f"""  <main id="main">
    <section class="hero" aria-labelledby="hero-title">
      <div class="glow" aria-hidden="true"></div>
      <div class="wrap hero-grid">
        <div>
          <p class="eyebrow">{esc(hero['eyebrow'])}</p>
          <h1 id="hero-title">{hero['title_html']}</h1>
          <p class="lead">{hero['lead']}</p>
          <div class="cta">
            <a class="btn primary" href="{LATEST}">{esc(hero['download'])}</a>
            <a class="btn" href="#tour">{esc(hero['tour'])}</a>
          </div>
          <ul class="chips" aria-label="{esc(hero['chips_label'])}">{chips}</ul>
        </div>
        {figure('desktop', 1280, 800, hero['alt'], prefix, lazy=False)}
      </div>
    </section>
""")

    t = s["tour"]
    rows = []
    for index, item in enumerate(t["items"]):
        side = " flip" if index % 2 else ""
        rows.append(f"""        <article class="feature{side}">
          <div class="copy">
            <p class="kicker">{esc(item['kicker'])}</p>
            <h3>{esc(item['title'])}</h3>
            <p>{item['text']}</p>
          </div>
          {figure(item['img'], item['w'], item['h'], item['alt'], prefix)}
        </article>""")
    out.append(f"""    <section id="tour" class="wrap" aria-labelledby="tour-title">
      <h2 id="tour-title">{esc(t['title'])}</h2>
      <p class="intro">{t['intro']}</p>
      <div class="features">
{chr(10).join(rows)}
      </div>
    </section>
""")

    i = s["inside"]
    groups = []
    for group in i["groups"]:
        items = "".join(f"<li><strong>{esc(name)}</strong> {text}</li>" for name, text in group["items"])
        groups.append(f"""        <article class="group"><h3><span class="gi" aria-hidden="true">{group['icon']}</span> {esc(group['title'])}</h3>
          <ul>{items}</ul></article>""")
    out.append(f"""    <section id="inside" class="band" aria-labelledby="inside-title">
      <div class="wrap">
        <h2 id="inside-title">{esc(i['title'])}</h2>
        <p class="intro">{i['intro']}</p>
        <div class="groups">
{chr(10).join(groups)}
        </div>
      </div>
    </section>
""")

    c = s["compare"]
    us = ' class="us"'
    header = "".join(f'<th scope="col"{us if k == 1 else ""}>{esc(h)}</th>' for k, h in enumerate(c["headers"]))
    body = []
    for row in c["rows"]:
        cells = "".join(f'<td{us if k == 0 else ""}>{status(kind, text)}</td>'
                        for k, (kind, text) in enumerate(row["cells"]))
        body.append(f'<tr><th scope="row">{esc(row["label"])}</th>{cells}</tr>')
    legend = " · ".join(f'<span aria-hidden="true">{MARK[k]}</span> {esc(c["legend"][k])}' for k in ("ok", "part", "no"))
    out.append(f"""    <section id="compare" class="wrap" aria-labelledby="compare-title">
      <h2 id="compare-title">{esc(c['title'])}</h2>
      <p class="intro">{c['intro']}</p>
      <div class="table-wrap" role="region" aria-labelledby="compare-title" tabindex="0">
        <table class="compare">
          <caption class="sr-only">{esc(c['caption'])}</caption>
          <thead><tr>{header}</tr></thead>
          <tbody>
            {(chr(10) + '            ').join(body)}
          </tbody>
        </table>
      </div>
      <p class="legend">{legend}</p>
      <p class="fine">{c['note']}</p>
    </section>
""")

    w = s["windows"]
    steps = "".join(f"<li>{step}</li>" for step in w["steps"])
    out.append(f"""    <section id="windows" class="wrap" aria-labelledby="windows-title">
      <h2 id="windows-title">{esc(w['title'])}</h2>
      <p class="intro">{w['intro']}</p>
      <ol class="steps">{steps}</ol>
      <p><a href="{GITHUB}/blob/main/docs/FROM-WINDOWS.md">{esc(w['guide'])}</a></p>
    </section>
""")

    h = s["honest"]
    head_cells = "".join(f'<th scope="col">{esc(x)}</th>' for x in h["headers"])
    honest_rows = "".join(f"<tr><td>{what}</td><td>{status(kind, text)}</td><td>{alternative}</td></tr>"
                          for what, kind, text, alternative in h["rows"])
    out.append(f"""    <section id="honest" class="wrap" aria-labelledby="honest-title">
      <h2 id="honest-title">{esc(h['title'])}</h2>
      <p class="intro">{h['intro']}</p>
      <div class="table-wrap" role="region" aria-labelledby="honest-title" tabindex="0">
        <table>
          <caption class="sr-only">{esc(h['caption'])}</caption>
          <thead><tr>{head_cells}</tr></thead>
          <tbody>{honest_rows}</tbody>
        </table>
      </div>
    </section>
""")

    d = s["download"]
    editions = "".join(f"""<article class="edition{' main' if k == 0 else ''}"><h3>{esc(e['name'])}</h3><p>{e['text']}</p></article>"""
                       for k, e in enumerate(d["editions"]))
    needs = "".join(f"<li>{x}</li>" for x in d["requirements"])
    out.append(f"""    <section id="download" class="band" aria-labelledby="download-title">
      <div class="wrap">
        <h2 id="download-title">{esc(d['title'])}</h2>
        <p class="intro">{d['intro']}</p>
        <div class="editions">{editions}</div>
        <div class="get">
          <div>
            <h3>{esc(d['requirements_title'])}</h3>
            <ul class="needs">{needs}</ul>
          </div>
          <div class="get-cta">
            <a class="btn primary big" href="{LATEST}">{esc(d['cta'])}</a>
            <a href="{GITHUB}/releases">{esc(d['all'])}</a>
            <p class="note">{d['note']}</p>
          </div>
        </div>
      </div>
    </section>
""")

    q = s["faq"]
    faqs = "".join(f"<details><summary>{esc(question)}</summary><p>{answer}</p></details>" for question, answer in q["items"])
    out.append(f"""    <section id="faq" class="wrap" aria-labelledby="faq-title">
      <h2 id="faq-title">{esc(q['title'])}</h2>
      {faqs}
    </section>
  </main>
""")
    out.append(footer(s, folder, switcher))
    return "".join(out)


def legal(s: dict, lang: str, page: str) -> str:
    body = (SRC / "legal" / lang / f"{page}.html").read_text(encoding="utf-8")
    match = re.match(r"<!-- title: (.+?) -->\n<!-- description: (.+?) -->\n", body)
    if not match:
        raise SystemExit(f"{lang}/{page}.html: the first two lines must be the title and description comments")
    title, description = match.groups()
    body = body[match.end():]
    folder = "" if lang == "he" else "en"
    prefix = "../" if folder else ""
    home = "index.html"
    other = (f"en/{page}.html", "en", "English") if lang == "he" else (f"../{page}.html", "he", "עברית")
    url = f"{DOMAIN}/{folder + '/' if folder else ''}{page}.html"
    nav = (f'\n      <nav class="main" aria-label="{esc(s["nav"]["label"])}"><a href="{other[0]}" hreflang="{other[1]}" '
           f'lang="{other[1]}">{other[2]}</a></nav>')
    return (head(s, f"{title} — D.Ai OS", description, prefix, url) + top(s, prefix, home, nav)
            + f'  <main id="main" class="wrap page">\n{body.rstrip()}\n  </main>\n' + footer(s, folder, ""))


def outputs() -> dict[Path, str]:
    pages: dict[Path, str] = {}
    strings = {}
    for code, folder, _ in languages.LANGS:
        s = json.loads((SRC / "strings" / f"{code}.json").read_text(encoding="utf-8"))
        assert s["lang"] == code, code
        strings[code] = s
        pages[SITE / folder / "index.html" if folder else SITE / "index.html"] = landing(s, folder)
    for page in LEGAL_PAGES:
        pages[SITE / f"{page}.html"] = legal(strings["he"], "he", page)
        pages[SITE / "en" / f"{page}.html"] = legal(strings["en"], "en", page)
    urls = [f"{DOMAIN}/"] + [f"{DOMAIN}/{folder}/" for _, folder, _ in languages.LANGS if folder]
    urls += [f"{DOMAIN}/{page}.html" for page in LEGAL_PAGES] + [f"{DOMAIN}/en/{page}.html" for page in LEGAL_PAGES]
    pages[SITE / "sitemap.xml"] = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                                   '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                                   + "".join(f"  <url><loc>{u}</loc></url>\n" for u in urls) + "</urlset>\n")
    return pages


def main(argv: list[str]) -> int:
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(SITE)))
            if "--check" not in argv:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if "--check" in argv and stale:
        print("out of date (run build/scripts/site-build.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
